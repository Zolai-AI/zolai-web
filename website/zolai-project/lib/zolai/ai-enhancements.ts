/**
 * Reusable AI Enhancement Utilities for Tutor & Chat
 * Shared functions for error correction, context memory, confidence scoring, etc.
 */

export interface ResponseEnhancement {
  original: string;
  withCorrection?: string;
  confidence?: number;
  source?: string;
  alternatives?: string[];
  culturalContext?: string;
  pronunciation?: string;
}

export interface ConversationMemory {
  userId: string;
  sessionId: string;
  learningTopics: string[];
  mistakePatterns: string[];
  successPatterns: string[];
  lastUpdated: Date;
}

/**
 * Error Correction Feedback
 * Analyzes response and provides structured correction
 */
export function generateErrorFeedback(
  userInput: string,
  correctForm: string,
  errorType: "grammar" | "vocabulary" | "pronunciation" | "dialect"
): string {
  const feedback: Record<string, string> = {
    grammar: `Grammar correction: "${userInput}" → "${correctForm}"\nRule: Check SOV word order (Subject-Object-Verb)`,
    vocabulary: `Vocabulary correction: "${userInput}" → "${correctForm}"\nNote: Use Tedim ZVS standard (pasian, gam, tapa, not pathian, ram, fapa)`,
    pronunciation: `Pronunciation: "${userInput}" should sound like "${correctForm}"\nTip: Remember "o" = /oʊ/ sound`,
    dialect: `Dialect correction: "${userInput}" → "${correctForm}"\nContext: This is the Tedim ZVS standard form`,
  };
  return feedback[errorType] || feedback.grammar;
}

/**
 * Confidence Scoring
 * Returns confidence level (0-1) based on response certainty
 */
export function scoreConfidence(
  response: string,
  hasSourceAttribution: boolean,
  isFromCorpus: boolean
): number {
  let score = 0.5; // base
  if (hasSourceAttribution) score += 0.2;
  if (isFromCorpus) score += 0.3;
  if (response.length > 50) score += 0.1; // longer = more detailed
  return Math.min(score, 1);
}

/**
 * Source Attribution
 * Adds source reference to response
 */
export function addSourceAttribution(
  response: string,
  source: "bible" | "dictionary" | "wiki" | "corpus" | "ai"
): string {
  const sources: Record<string, string> = {
    bible: "[Source: Bible Corpus - TDB77/TBR17/Tedim2010]",
    dictionary: "[Source: Zolai Dictionary - 24,891 entries]",
    wiki: "[Source: Zolai Linguistics Wiki]",
    corpus: "[Source: Zolai Master Corpus]",
    ai: "[Generated by AI - verify with native speaker]",
  };
  return `${response}\n\n${sources[source]}`;
}

